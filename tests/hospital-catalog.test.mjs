import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';
import { seedHospitalCatalog, listResponseFacilities, hospitalCatalogInfo } from '../server/hospital-catalog.mjs';
import { createApp } from '../server/app.mjs';
import { hashPassword, digest, randomToken } from '../server/auth.mjs';

test('hospital import is idempotent, searchable and respects operator deletions', async t => {
  const db = new PGlite();
  await db.exec(await readFile(new URL('../server/schema.sql', import.meta.url),'utf8'));
  t.after(() => db.close());
  const customId = randomUUID();
  await db.query("insert into eligtas.response_facilities(id,kind,name,location) values ($1,'base','Test base',$2)", [customId,JSON.stringify({lat:14.58,lng:121.1,label:'Test base'})]);
  assert.equal(await seedHospitalCatalog(db), hospitalCatalogInfo.count);
  assert.equal(await seedHospitalCatalog(db), 0);
  const all = await listResponseFacilities(db, {kind:'hospital'});
  assert.equal(all.total,1837);
  assert.equal(all.facilities.length,30);
  const manila = await listResponseFacilities(db,{q:'Philippine General',kind:'hospital'});
  assert.ok(manila.facilities.some(h=>h.name.includes('Philippine General')));
  assert.equal((await listResponseFacilities(db,{q:"%' OR 1=1 --"})).total,0);
  const next = await listResponseFacilities(db,{kind:'hospital',offset:30});
  assert.ok(next.facilities.every(h=>!all.facilities.some(f=>f.id===h.id)));
  const records=(await db.query("select * from eligtas.response_facilities where kind='hospital'")).rows;
  assert.ok(records.every(h=>h.location.lat>4 && h.location.lat<22 && h.location.lng>116 && h.location.lng<127 && /^https:\/\/www.openstreetmap.org\/(node|way|relation)\/\d+$/.test(h.source_data.sourceUrl)));
  assert.ok(records.some(h=>h.location.lat<8));
  assert.ok(records.some(h=>h.location.lat>18));

  const adminId=randomUUID(), token=randomToken();
  await db.query("insert into eligtas.users(id,username,name,password_hash,recovery_hash,role) values($1,'catalog_admin','Test operator',$2,$2,'admin')",[adminId,await hashPassword('catalog-test-password-2026')]);
  await db.query("insert into eligtas.sessions(token_hash,user_id,expires_at) values($1,$2,now()+interval '1 hour')",[digest(token),adminId]);
  const app=createApp(db,{allowedOrigins:['http://test.local']});
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const base=`http://127.0.0.1:${server.address().port}/api`;
  const headers={Cookie:'eligtas_session='+token,Origin:'http://test.local','Content-Type':'application/json'};
  assert.equal((await fetch(base+'/response-facilities')).status,401);
  assert.equal((await fetch(base+'/response-facilities?q=Philippine%20General',{headers})).status,200);
  const target=manila.facilities[0];
  assert.equal((await fetch(base+'/response-facilities/'+target.id,{method:'DELETE',headers,body:'{}'})).status,200);
  await db.query('delete from eligtas.settings where key=$1',['hospital_catalog_'+hospitalCatalogInfo.version]);
  assert.equal(await seedHospitalCatalog(db),0);
  assert.equal((await db.query('select id from eligtas.response_facilities where id=$1',[target.id])).rows.length,0);
  assert.equal((await db.query('select id from eligtas.response_facilities where id=$1',[customId])).rows.length,1);
  const state=await (await fetch(base+'/state',{headers})).json();
  assert.equal(state.hospitalDirectoryReady,true);
  assert.equal(state.responseDirectoryCounts.hospital,1836);
  assert.equal(state.responseFacilities.length,1,'polling should not repeat the nationwide catalog');
});
